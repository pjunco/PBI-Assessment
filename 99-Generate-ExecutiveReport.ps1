Write-Host "Input folder : $OutputFolder" -ForegroundColor Gray

# ── 2. Parse data ────────────────────────────────────────────────────────────
$ws         = Get-Content $wsFile  -Raw | ConvertFrom-Json
$allData    = Get-Content $allFile -Raw | ConvertFrom-Json
$allReports = @($allData | ForEach-Object { $_.Reports } | Where-Object { $_ -ne $null })
$allDS      = @($allReports | ForEach-Object { $_.DataSources } | Where-Object { $_ -ne $null })

# ── KPIs ─────────────────────────────────────────────────────────────────────
$totalWS      = $ws.Count
$fabricWS     = ($ws | Where-Object { $_.CapacityType -eq 'Fabric Capacity' }).Count
$premiumWS    = ($ws | Where-Object { $_.CapacityType -eq 'PBI Premium Capacity' }).Count
$emptyWS      = ($ws | Where-Object { $_.ReportCount -eq 0 }).Count
$totalReports = $allReports.Count
$importR      = ($allReports | Where-Object { $_.ConnectionMode -eq 'Import' }).Count
$dqR          = ($allReports | Where-Object { $_.ConnectionMode -like 'DirectQuery*' -or $_.ConnectionMode -like 'Direct*' }).Count
$unkR         = ($allReports | Where-Object { $_.ConnectionMode -eq 'Unknown' }).Count

$importPct = if ($totalReports -gt 0) { [math]::Round($importR / $totalReports * 100, 1) } else { 0 }
$dqPct     = if ($totalReports -gt 0) { [math]::Round($dqR     / $totalReports * 100, 1) } else { 0 }

# ── SKU breakdown ─────────────────────────────────────────────────────────────
$skuGroups = $ws | Group-Object CapacitySku | Sort-Object Count -Descending
$skuLabels = ($skuGroups | ForEach-Object { "'$($_.Name) ($($_.Count))'" }) -join ','
$skuData   = ($skuGroups | ForEach-Object { $_.Count }) -join ','
$skuNames  = ($skuGroups | ForEach-Object { "'$($_.Name)'" }) -join ','

# ── Capacity name breakdown ───────────────────────────────────────────────────
$capGroups  = $ws | Group-Object CapacityName | Sort-Object Count -Descending | Select-Object -First 8
$capLabels  = ($capGroups | ForEach-Object { $n = $_.Name; if ($n.Length -gt 22) { $n = $n.Substring(0,20)+'…' }; "'$n'" }) -join ','
$capData    = ($capGroups | ForEach-Object { $_.Count }) -join ','

# ── Top data sources ─────────────────────────────────────────────────────────
$dsGroups = $allDS | Where-Object { $_.datasourceName } | Group-Object datasourceName |
            Sort-Object Count -Descending | Select-Object -First 10
$dsLabels = ($dsGroups | ForEach-Object { "'$($_.Name)'" }) -join ','
$dsData   = ($dsGroups | ForEach-Object { $_.Count }) -join ','

# ── Top 10 workspaces by report count ────────────────────────────────────────
$top10       = $ws | Sort-Object ReportCount -Descending | Select-Object -First 10
$top10Labels = ($top10 | ForEach-Object { $n = $_.Name; if ($n.Length -gt 28) { $n = $n.Substring(0,26)+'…' }; "'$n'" }) -join ','
$top10Data   = ($top10 | ForEach-Object { $_.ReportCount }) -join ','
$top10Colors = ($top10 | ForEach-Object { if ($_.CapacityType -eq 'Fabric Capacity') { "'#16a34a'" } else { "'#b11f4b'" } }) -join ','

# ── Workspace table JSON ─────────────────────────────────────────────────────
$wsSorted = $ws | Sort-Object ReportCount -Descending
$wsJsonRows = ($wsSorted | ForEach-Object {
    $n   = $_.Name    -replace "'", "\'"
    $cap = if ($_.CapacityName) { $_.CapacityName } else { 'Unknown' }
    $cap = $cap -replace "'", "\'"
    $sf  = if ($_.DefaultDatasetStorageFormat) { $_.DefaultDatasetStorageFormat } else { 'Small' }
    "{ name:'$n', cap:'$cap', sku:'$($_.CapacitySku)', type:'$($_.CapacityType)', reports:$($_.ReportCount), storage:'$sf' }"
}) -join (",`n    ")

# ── Fabric workspace names ────────────────────────────────────────────────────
$fabricNames = ($ws | Where-Object { $_.CapacityType -eq 'Fabric Capacity' } | ForEach-Object { $_.Name }) -join ' &nbsp;·&nbsp; '
if (-not $fabricNames) { $fabricNames = 'Nenhum' }
$fabricSku  = ($ws | Where-Object { $_.CapacityType -eq 'Fabric Capacity' } | Select-Object -First 1 -ExpandProperty CapacitySku)
if (-not $fabricSku) { $fabricSku = 'N/A' }
$fabricCap  = ($ws | Where-Object { $_.CapacityType -eq 'Fabric Capacity' } | Select-Object -First 1 -ExpandProperty CapacityName)
if (-not $fabricCap) { $fabricCap = 'N/A' }

# ── LSM check ────────────────────────────────────────────────────────────────
$lsmEnabled = ($ws | Where-Object { $_.DefaultDatasetStorageFormat -eq 'Large' }).Count
$lsmText    = if ($lsmEnabled -gt 0) { "$lsmEnabled $($T.lsmEnabledTxt)" } else { $T.lsmDisabledTxt }

$reportDate = (Get-Date).ToString($T.dateFormat, [System.Globalization.CultureInfo]::GetCultureInfo($T.dateLocale))

Write-Host "  Language    : $($T.htmlLang)" -ForegroundColor Gray
Write-Host "  Workspaces  : $totalWS (Fabric: $fabricWS, Premium: $premiumWS)" -ForegroundColor Gray
Write-Host "  Reports     : $totalReports (Import: $importPct%, DQ: $dqPct%)" -ForegroundColor Gray

