.SYNOPSIS
    Generates a self-contained HTML executive report from PBI Assessment output files.

.DESCRIPTION
    Reads PowerBI_Workspaces.json and PowerBI_Reports_All_Workspaces.json from a given
    output folder and produces an interactive HTML report with charts, KPIs, workspace
    table, data sources breakdown, and strategic findings.

.PARAMETER OutputFolder
    Path to the folder containing the assessment JSON output files.
    Defaults to .\Output-BRA

.PARAMETER CustomerName
    Display name of the customer. Defaults to folder name.

.PARAMETER ReportPath
    Path for the generated HTML file.
    Defaults to <OutputFolder>\Executive_Report_<CustomerName>.html

.EXAMPLE
    .\Generate-ExecutiveReport.ps1 -OutputFolder .\Output-BRA -CustomerName "Claro Brazil"

.PARAMETER Language
    Report language. 1 = English, 2 = Spanish, 3 = Portuguese (default).

.EXAMPLE
    .\Generate-ExecutiveReport.ps1 -OutputFolder .\Output-AMX -CustomerName "AMX Mexico" -Language 2
#>

