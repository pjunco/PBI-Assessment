    $safeName = $CustomerName -replace '[\\/:*?"<>| ]', '_'
    $ReportPath = Join-Path $OutputFolder "Executive_Report_$safeName.html"
}

$wsFile  = Join-Path $OutputFolder "PowerBI_Workspaces.json"
$allFile = Join-Path $OutputFolder "PowerBI_Reports_All_Workspaces.json"

if (-not (Test-Path $wsFile))  { throw "File not found: $wsFile" }
if (-not (Test-Path $allFile)) { throw "File not found: $allFile" }

Write-Host ""
