.PARAMETER CustomerName
    Display name shown in the report header.
    Defaults to the folder name.

.PARAMETER ReportPath
    Full path for the generated HTML file.
    Defaults to <OutputFolder>\PowerBI_UsageReport_<CustomerName>.html

.PARAMETER Language
    Report language: 1 = English (default), 2 = Spanish, 3 = Portuguese.

.EXAMPLE
    .\05-Generate-UsageReport.ps1

.EXAMPLE
    .\05-Generate-UsageReport.ps1 -OutputFolder .\Output-AMX -CustomerName "AMX Mexico" -Language 2
#>

