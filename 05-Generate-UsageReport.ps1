        "Only $dormancyPct% of reports ($dormantReports out of $totalReports) were inactive. Report adoption is healthy — most published reports are being used."
    }
    $fConcText   = "The top 5 reports account for $top5Pct% of all views. While this shows a clear set of high-value reports, consider promoting other reports to a broader audience."
    $fWebText    = "Power BI Web is the primary access channel. Ensure reports are optimized for browser rendering and that page load times are acceptable."
    $fMobileText = "Mobile access represents $mobilePct% of views. Ensure key reports are optimized with a mobile layout using Power BI Desktop's Phone View."
    $fNoDataText = "No view events were captured in the selected period. Verify that the Power BI Administrator role is assigned and that the Activity Events API is enabled in tenant settings."
} elseif ($Language -eq 2) {
    $fDormText   = if ($dormancyPct -ge 50) {
        "$dormancyPct% de los reportes ($dormantReports de $totalReports) no tuvieron vistas en los últimos $periodDays días. Se recomienda archivar el contenido no utilizado."
    } else {
        "Solo $dormancyPct% de los reportes estuvieron inactivos. La adopción es saludable — la mayoría de los reportes publicados están siendo utilizados."
    }
    $fConcText   = "Los 5 reportes más vistos concentran el $top5Pct% de todas las vistas. Considere promover otros reportes para ampliar el alcance."
    $fWebText    = "Power BI Web es el canal de acceso principal. Optimice los reportes para el navegador y verifique los tiempos de carga."
    $fMobileText = "El acceso móvil representa el $mobilePct% de las vistas. Asegúrese de que los reportes clave tengan un diseño optimizado para teléfono."
    $fNoDataText = "No se capturaron eventos de vista en el período. Verifique el rol de Administrador de Power BI y la configuración de la API de eventos de actividad."
} else {
    $fDormText   = if ($dormancyPct -ge 50) {
        "$dormancyPct% dos relatórios ($dormantReports de $totalReports) não tiveram visualizações nos últimos $periodDays dias. Considere arquivar conteúdo não utilizado."
    } else {
        "Apenas $dormancyPct% dos relatórios estiveram inativos. A adoção está saudável — a maioria dos relatórios publicados está sendo usada."
    }
    $fConcText   = "Os 5 relatórios mais vistos concentram $top5Pct% de todas as visualizações. Considere promover outros relatórios para ampliar o alcance."
    $fWebText    = "Power BI Web é o canal de acesso principal. Otimize os relatórios para o navegador e verifique os tempos de carregamento."
    $fMobileText = "Acesso mobile representa $mobilePct% das visualizações. Certifique-se de que os principais relatórios têm layout otimizado para celular."
    $fNoDataText = "Nenhum evento de visualização foi capturado no período. Verifique a função de Administrador do Power BI e as configurações da API de eventos de atividade."
}

# ── Optional: Azure Log Analytics query timings ───────────────────────────────
$laTimingJson = ''
$laDailyJson  = ''
$laHasData    = 0

$laAnswer = Read-Host "`nFetch server-side query performance from Azure Log Analytics? (Y/N)"
if ($laAnswer -match '^[Yy]') {
    $laWorkspaceId = (Read-Host "  Log Analytics Workspace ID (GUID)").Trim()
    $laToken = $null

    # Try Az.Accounts module
    if (Get-Command Get-AzAccessToken -ErrorAction SilentlyContinue) {
        try {
            $laToken = (Get-AzAccessToken -ResourceUrl 'https://api.loganalytics.io' -ErrorAction Stop).Token
            Write-Host "  Auth: Az.Accounts OK" -ForegroundColor Green
        } catch { Write-Warning "Az.Accounts failed: $_" }
    }
    # Fallback: az CLI
    if (-not $laToken) {
        try {
            $t = (az account get-access-token --resource 'https://api.loganalytics.io' --query accessToken -o tsv 2>$null)
            if ($t) { $laToken = $t.Trim(); Write-Host "  Auth: az CLI OK" -ForegroundColor Green }
        } catch {}
    }

    if (-not $laToken) {
        Write-Warning "Could not get a Log Analytics token.`n  Install Az.Accounts:  Install-Module Az.Accounts`n  Or install az CLI:     https://aka.ms/installazurecliwindows"
    } else {
        function Invoke-LAQuery {
            param($WsId, $Token, $Kql)
            $body    = [System.Text.Encoding]::UTF8.GetBytes((ConvertTo-Json @{ query = $Kql } -Compress))
            $headers = @{ Authorization = "Bearer $Token"; 'Content-Type' = 'application/json' }
            Invoke-RestMethod -Method POST -Uri "https://api.loganalytics.io/v1/workspaces/$WsId/query" `
                -Headers $headers -Body $body -ErrorAction Stop
        }
        $sd = $periodStart
        $ed = $periodEnd
        $md = if ($periodMid) { $periodMid } else { $periodStart }

        # Per-report: P25/P50/P75 + first-half vs second-half P50
        $kqlReport = "let sd=datetime('$sd');let ed=datetime('$ed');let md=datetime('$md');PowerBIDatasetsWorkspace|where TimeGenerated between(sd..ed)|where OperationName=='AnalysisServices.QueryEnd' and isnotempty(ReportId) and Duration>0|extend h=iff(TimeGenerated<md,1,2)|summarize p25=round(percentile(Duration,25)),p50=round(percentile(Duration,50)),p75=round(percentile(Duration,75)),ph1=round(percentileif(Duration,50,h==1)),ph2=round(percentileif(Duration,50,h==2)),cnt=count() by rid=tostring(ReportId),rname=tostring(ReportName),wsname=tostring(WorkspaceName)|order by cnt desc|limit 50"
        try {
            Write-Host "  Querying per-report timings..." -ForegroundColor Cyan
            $rptRes = Invoke-LAQuery -WsId $laWorkspaceId -Token $laToken -Kql $kqlReport
            $cols   = @($rptRes.tables[0].columns.name)
            $parts  = foreach ($row in $rptRes.tables[0].rows) {
                $o = @{}; for ($i = 0; $i -lt $cols.Count; $i++) { $o[$cols[$i]] = $row[$i] }
                $ph1 = if ($o['ph1']) { [int]$o['ph1'] } else { 0 }
                $ph2 = if ($o['ph2']) { [int]$o['ph2'] } else { 0 }
                "{`"rid`":`"$(EscJs $o['rid'])`",`"rname`":`"$(EscJs $o['rname'])`",`"wsname`":`"$(EscJs $o['wsname'])`",`"p25`":$([int]$o['p25']),`"p50`":$([int]$o['p50']),`"p75`":$([int]$o['p75']),`"ph1`":$ph1,`"ph2`":$ph2,`"cnt`":$([int]$o['cnt'])}"
            }
            $laTimingJson = $parts -join ','
            Write-Host "    $($rptRes.tables[0].rows.Count) reports with timing data" -ForegroundColor Green
        } catch { Write-Warning "Per-report timing query failed: $_" }

        # Daily aggregate P25/P50/P75 across all queries
        $kqlDaily = "let sd=datetime('$sd');let ed=datetime('$ed');PowerBIDatasetsWorkspace|where TimeGenerated between(sd..ed)|where OperationName=='AnalysisServices.QueryEnd' and Duration>0|summarize p25=round(percentile(Duration,25)),p50=round(percentile(Duration,50)),p75=round(percentile(Duration,75)) by d=format_datetime(bin(TimeGenerated,1d),'yyyy-MM-dd')|order by d asc"
        try {
            Write-Host "  Querying daily timings..." -ForegroundColor Cyan
            $dayRes = Invoke-LAQuery -WsId $laWorkspaceId -Token $laToken -Kql $kqlDaily
            $cols   = @($dayRes.tables[0].columns.name)
            $dparts = foreach ($row in $dayRes.tables[0].rows) {
                $o = @{}; for ($i = 0; $i -lt $cols.Count; $i++) { $o[$cols[$i]] = $row[$i] }
                "{`"d`":`"$($o['d'])`",`"p25`":$([int]$o['p25']),`"p50`":$([int]$o['p50']),`"p75`":$([int]$o['p75'])}"
            }
            $laDailyJson = $dparts -join ','
            Write-Host "    $($dayRes.tables[0].rows.Count) days with timing data" -ForegroundColor Green
        } catch { Write-Warning "Daily timing query failed: $_" }

        if ($laTimingJson -or $laDailyJson) { $laHasData = 1 }
    }
}

