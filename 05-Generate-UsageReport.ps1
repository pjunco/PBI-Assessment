  if (!D.browserLabels || !D.browserLabels.length || D.totalViews === 0) {
    const el = document.getElementById('browserChart');
    if (el) el.closest('.chart-card').style.opacity = '0.4';
    return;
  }
  const palette = ['#0078d4','#16a34a','#f59e0b','#dc2626','#8b5cf6','#0ea5e9','#ec4899','#94a3b8'];
  new Chart(document.getElementById('browserChart'), {
    type: 'doughnut',
    data: {
      labels: D.browserLabels,
      datasets: [{ data: D.browserData, backgroundColor: palette, hoverOffset: 6, borderWidth: 2 }]
    },
    options: {
      responsive: true, maintainAspectRatio: true,
      plugins: { legend: { position: 'bottom', labels: { font: { size: 11 }, boxWidth: 14 } } }
    }
  });
}

// ── PERFORMANCE TREND TABLE ───────────────────────────────────────────────────
function buildPerfTable() {
  const tbody = document.getElementById('perfTableBody');
  if (!D.perfData || !D.perfData.length) {
    tbody.innerHTML = '<tr><td colspan="8" style="text-align:center;color:var(--cp-text-muted);padding:20px">—</td></tr>';
    return;
  }
  const trendIcon = { up: '↑', down: '↓', flat: '→' };
  const trendStyle = {
    up:   'color:var(--cp-success);font-size:1.1rem;font-weight:700',
    down: 'color:var(--cp-danger);font-size:1.1rem;font-weight:700',
    flat: 'color:var(--cp-text-muted);font-size:1.1rem'
  };
  tbody.innerHTML = D.perfData.map(r => {
    const nameCell = r.url
      ? '<a class="report-link" href="'+r.url+'" target="_blank">'+r.name+'</a>'
      : r.name;
    const t = r.trend || 'flat';
    return '<tr>'+
      '<td style="max-width:240px;overflow:hidden;text-overflow:ellipsis;white-space:nowrap" title="'+r.name+'">'+nameCell+'</td>'+
      '<td style="max-width:160px;overflow:hidden;text-overflow:ellipsis;white-space:nowrap">'+r.ws+'</td>'+
      '<td style="text-align:right">'+r.views.toLocaleString()+'</td>'+
      '<td style="text-align:right">'+r.viewers.toLocaleString()+'</td>'+
      '<td style="text-align:right">'+r.firstH.toLocaleString()+'</td>'+
      '<td style="text-align:right">'+r.secH.toLocaleString()+'</td>'+
      '<td style="text-align:center;'+trendStyle[t]+'">'+trendIcon[t]+'</td>'+
      '<td>'+(r.method||'-')+'</td>'+
    '</tr>';
  }).join('');
}

