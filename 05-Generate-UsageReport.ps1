# ── Load data ─────────────────────────────────────────────────────────────────
$usagePath = Join-Path $OutputFolder "PowerBI_UsageMetrics_All.json"
if (-not (Test-Path $usagePath)) {
    throw "Input file not found: $usagePath`nRun 03-Get-UsageMetricByReport.ps1 first."
}

$usageData = Get-Content $usagePath -Raw | ConvertFrom-Json
if (-not $usageData -or $usageData.Count -eq 0) {
    throw "Input file is empty or invalid."
}

if (-not $CustomerName) {
    $CustomerName = (Split-Path (Resolve-Path $OutputFolder) -Leaf)
}
if (-not $ReportPath) {
    $safe = $CustomerName -replace '[\\/:*?"<>|]', '_'
    $ReportPath = Join-Path $OutputFolder "PowerBI_UsageReport_$safe.html"
}

Write-Host "Loading usage data for: $CustomerName" -ForegroundColor Cyan

# ── Flatten all reports ────────────────────────────────────────────────────────
$allReports = [System.Collections.Generic.List[object]]::new()
foreach ($ws in $usageData) {
    foreach ($rpt in $ws.Reports) {
        $allReports.Add([PSCustomObject]@{
            WorkspaceName         = $ws.WorkspaceName
            CapacityType          = $ws.CapacityType
            WorkspaceId           = $ws.WorkspaceId
            ReportId              = $rpt.ReportId
            ReportName            = $rpt.ReportName
            WebUrl                = if ($rpt.WebUrl) { $rpt.WebUrl } else { '' }
            TotalViews            = [int]$rpt.TotalViews
            TotalUniqueViewers    = [int]$rpt.TotalUniqueViewers
            TotalShares           = [int]$rpt.TotalShares
            RankByTotalViewsInOrg = $rpt.RankByTotalViewsInOrg
            ViewsPerDay           = $rpt.ViewsPerDay
            AccessMethodBreakdown = $rpt.AccessMethodBreakdown
            BrowserBreakdown      = $rpt.BrowserBreakdown
            MostViewedPages       = $rpt.MostViewedPages
        })
    }
}

# ── KPIs ──────────────────────────────────────────────────────────────────────
$totalViews     = [int]($allReports | Measure-Object TotalViews -Sum).Sum
$totalViewers   = [int]($allReports | Where-Object { $_.TotalUniqueViewers -gt 0 } |
                        Measure-Object TotalUniqueViewers -Sum).Sum
$totalShares    = [int]($allReports | Measure-Object TotalShares -Sum).Sum
$activeReports  = ($allReports | Where-Object { $_.TotalViews -gt 0 }).Count
$totalReports   = $allReports.Count
$dormantReports = $totalReports - $activeReports
$activePct      = if ($totalReports -gt 0) { [Math]::Round($activeReports / $totalReports * 100, 1) } else { 0 }

$periodStart = if ($usageData[0].PeriodStartDate) { $usageData[0].PeriodStartDate } else { 'N/A' }
$periodEnd   = if ($usageData[0].PeriodEndDate)   { $usageData[0].PeriodEndDate }   else { 'N/A' }
$periodDays  = if ($usageData[0].PeriodDays)      { $usageData[0].PeriodDays }      else { 0 }

Write-Host "  $totalReports reports | $activeReports active | $totalViews total views" -ForegroundColor Gray

# ── Daily trend ────────────────────────────────────────────────────────────────
$dailyMap = @{}
foreach ($rpt in $allReports) {
    foreach ($day in $rpt.ViewsPerDay) {
        if ($day -and $day.Date) {
            $d = $day.Date
            if ($dailyMap.ContainsKey($d)) { $dailyMap[$d] += [int]$day.Views }
            else { $dailyMap[$d] = [int]$day.Views }
        }
    }
}
$sortedDays  = $dailyMap.Keys | Sort-Object
$trendLabels = if ($sortedDays) { ($sortedDays | ForEach-Object { "`"$_`"" }) -join ',' } else { '' }
$trendData   = if ($sortedDays) { ($sortedDays | ForEach-Object { $dailyMap[$_] }) -join ',' } else { '' }

# ── Top 15 reports ─────────────────────────────────────────────────────────────
$top15 = @($allReports | Sort-Object TotalViews -Descending | Select-Object -First 15)
function EscJs($s) { if ($s) { $s -replace '\\','\\' -replace '"','\"' -replace "`r`n",'\n' -replace "`n",'\n' } else { '' } }
$top15Labels = ($top15 | ForEach-Object { "`"$(EscJs $_.ReportName)`"" }) -join ','
$top15Data   = ($top15 | ForEach-Object { $_.TotalViews }) -join ','
$top15Urls   = ($top15 | ForEach-Object { "`"$(EscJs $_.WebUrl)`"" }) -join ','
$top15WS     = ($top15 | ForEach-Object { "`"$(EscJs $_.WorkspaceName)`"" }) -join ','

# ── Access method breakdown ────────────────────────────────────────────────────
$accessMap = @{}
foreach ($rpt in $allReports) {
    foreach ($m in $rpt.AccessMethodBreakdown) {
        if ($m -and $m.Method) {
            if ($accessMap.ContainsKey($m.Method)) { $accessMap[$m.Method] += [int]$m.Views }
            else { $accessMap[$m.Method] = [int]$m.Views }
        }
    }
}
$accessLabels = if ($accessMap.Count -gt 0) { ($accessMap.Keys | ForEach-Object { "`"$(EscJs $_)`"" }) -join ',' } else { '"No data"' }
$accessData   = if ($accessMap.Count -gt 0) { ($accessMap.Keys | ForEach-Object { $accessMap[$_] }) -join ',' } else { '0' }

# ── Browser breakdown ──────────────────────────────────────────────────────────
$browserMap = @{}
foreach ($rpt in $allReports) {
    foreach ($b in $rpt.BrowserBreakdown) {
        if ($b -and $b.Browser) {
            if ($browserMap.ContainsKey($b.Browser)) { $browserMap[$b.Browser] += [int]$b.Views }
            else { $browserMap[$b.Browser] = [int]$b.Views }
        }
    }
}
$browserLabels = if ($browserMap.Count -gt 0) { ($browserMap.Keys | Sort-Object { -$browserMap[$_] } | ForEach-Object { "`"$(EscJs $_)`"" }) -join ',' } else { '' }
$browserData   = if ($browserMap.Count -gt 0) { ($browserMap.Keys | Sort-Object { -$browserMap[$_] } | ForEach-Object { $browserMap[$_] }) -join ',' } else { '' }

# ── Performance trend table (top active reports, first-half vs second-half) ────
$periodMid = if ($sortedDays -and $sortedDays.Count -gt 1) { $sortedDays[[math]::Floor($sortedDays.Count / 2)] } else { '' }
$perfTableParts = foreach ($rpt in ($allReports | Where-Object { $_.TotalViews -gt 0 } | Sort-Object TotalViews -Descending | Select-Object -First 15)) {
    $firstH = if ($periodMid) { [int](($rpt.ViewsPerDay | Where-Object { $_.Date -lt $periodMid } | Measure-Object Views -Sum).Sum) } else { 0 }
    $secH   = if ($periodMid) { [int](($rpt.ViewsPerDay | Where-Object { $_.Date -ge $periodMid } | Measure-Object Views -Sum).Sum) } else { [int]$rpt.TotalViews }
    $trend  = if   ($firstH -eq 0 -and $secH -eq 0) { 'flat' }
              elseif ($firstH -eq 0)                 { 'up'   }
              elseif ($secH   -eq 0)                 { 'down' }
              elseif ($secH -gt [int]($firstH * 1.1)) { 'up'  }
              elseif ($secH -lt [int]($firstH * 0.9)) { 'down'}
              else                                   { 'flat' }
    $topMethod = if ($rpt.AccessMethodBreakdown -and @($rpt.AccessMethodBreakdown).Count -gt 0) { EscJs $rpt.AccessMethodBreakdown[0].Method } else { '' }
    "{`"name`":`"$(EscJs $rpt.ReportName)`",`"ws`":`"$(EscJs $rpt.WorkspaceName)`",`"url`":`"$(EscJs $rpt.WebUrl)`",`"views`":$($rpt.TotalViews),`"viewers`":$($rpt.TotalUniqueViewers),`"firstH`":$firstH,`"secH`":$secH,`"trend`":`"$trend`",`"method`":`"$topMethod`"}"
}
$perfTableJson = if ($perfTableParts) { $perfTableParts -join ',' } else { '' }

# ── Workspace summary JSON ─────────────────────────────────────────────────────
$wsSummaryParts = foreach ($ws in $usageData) {
    $wsViews   = [int]($ws.Reports | Measure-Object TotalViews -Sum).Sum
    $wsActive  = ($ws.Reports | Where-Object { $_.TotalViews -gt 0 }).Count
    $wsViewers = [int]($ws.Reports | Where-Object { $_.TotalUniqueViewers -gt 0 } |
                       Measure-Object TotalUniqueViewers -Sum).Sum
    $wsTop     = @($ws.Reports | Sort-Object TotalViews -Descending) | Select-Object -First 1
    $topName   = if ($wsTop -and $wsTop.ReportName) { EscJs $wsTop.ReportName } else { '' }
    $topViews  = if ($wsTop) { [int]$wsTop.TotalViews } else { 0 }
    "{`"ws`":`"$(EscJs $ws.WorkspaceName)`",`"cap`":`"$(EscJs $ws.CapacityType)`",`"rCount`":$($ws.ReportCount),`"views`":$wsViews,`"viewers`":$wsViewers,`"active`":$wsActive,`"topRpt`":`"$topName`",`"topViews`":$topViews}"
}
$wsSummaryJson = $wsSummaryParts -join ','

# ── Report detail table JSON ───────────────────────────────────────────────────
$reportTableParts = foreach ($rpt in ($allReports | Sort-Object TotalViews -Descending)) {
    $topPage   = if ($rpt.MostViewedPages -and @($rpt.MostViewedPages).Count -gt 0) { EscJs $rpt.MostViewedPages[0].Page } else { '' }
    $topMethod = if ($rpt.AccessMethodBreakdown -and @($rpt.AccessMethodBreakdown).Count -gt 0) { EscJs $rpt.AccessMethodBreakdown[0].Method } else { '' }
    $rank      = if ($rpt.RankByTotalViewsInOrg) { [int]$rpt.RankByTotalViewsInOrg } else { 9999 }
    "{`"name`":`"$(EscJs $rpt.ReportName)`",`"ws`":`"$(EscJs $rpt.WorkspaceName)`",`"url`":`"$(EscJs $rpt.WebUrl)`",`"views`":$($rpt.TotalViews),`"viewers`":$($rpt.TotalUniqueViewers),`"shares`":$($rpt.TotalShares),`"rank`":$rank,`"topPage`":`"$topPage`",`"method`":`"$topMethod`"}"
}
$reportTableJson = $reportTableParts -join ','

# ── Findings data ─────────────────────────────────────────────────────────────
$dormancyPct = if ($totalReports -gt 0) { [Math]::Round($dormantReports / $totalReports * 100, 0) } else { 0 }
$top5Views   = [int]($top15 | Select-Object -First 5 | Measure-Object TotalViews -Sum).Sum
$top5Pct     = if ($totalViews -gt 0) { [Math]::Round($top5Views / $totalViews * 100, 0) } else { 0 }
$webViews    = if ($accessMap.ContainsKey('Power BI Web')) { $accessMap['Power BI Web'] } else { 0 }
$mobileViews = if ($accessMap.ContainsKey('Power BI Mobile')) { $accessMap['Power BI Mobile'] } else { 0 }
$mobilePct   = if ($totalViews -gt 0) { [Math]::Round($mobileViews / $totalViews * 100, 0) } else { 0 }
$generatedDate = (Get-Date -Format 'MMMM dd, yyyy')
$topWsName   = if ($usageData.Count -gt 0) {
    $usageData | ForEach-Object {
        $v = [int]($_.Reports | Measure-Object TotalViews -Sum).Sum
        [PSCustomObject]@{ Name=$_.WorkspaceName; Views=$v }
    } | Sort-Object Views -Descending | Select-Object -First 1 -ExpandProperty Name
} else { '' }

# ── Findings text (language-aware) ────────────────────────────────────────────
if ($Language -eq 1) {
    $fDormText   = if ($dormancyPct -ge 50) {
        "$dormancyPct% of reports ($dormantReports out of $totalReports) had zero views in the past $periodDays days. Consider archiving or retiring unused content to reduce clutter and maintenance overhead."
